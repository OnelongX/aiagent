# === 紧急情况触发词 ===
EMERGENCY_KEYWORDS = [
    "生命危险", "想死", "自杀", "家暴", "毒打",
    "强奸", "猥亵", "诈骗大额", "现在被打",
    "被绑架", "被关", "马上要", "正在",
]


def is_emergency(text: str) -> bool:
    """检测应急情况。"""
    lower = text.lower()
    return any(kw in lower for kw in EMERGENCY_KEYWORDS)


