# === 禁止 AI 直接给建议的关键词 ===
FORBIDDEN_PHRASES = [
    "你应该", "你应当", "建议你起诉", "建议你",
    "我建议", "你这案子能赢", "胜算", "胜诉率",
    "你必须", "毫无疑问", "100%",
]


def detect_legal_advice(text: str) -> list[str]:
    """检测输出是否含违规建议性语言。"""
    return [p for p in FORBIDDEN_PHRASES if p in text]


def soften_advice(text: str) -> str:
    """把建议性语言改写为科普性语言。"""
    replacements = {
        "你应该": "一般来说可以考虑",
        "你应当": "通常需要",
        "建议你起诉": "如需维权可以考虑诉讼途径",
        "建议你": "可以参考",
        "我建议": "一般而言",
        "你这案子能赢": "案件结果需由法院判决",
        "胜算": "案件走向需评估",
        "胜诉率": "案件结果需评估",
        "你必须": "通常需要",
        "毫无疑问": "一般认为",
        "100%": "通常情况下",
    }
    result = text
    for k, v in replacements.items():
        result = result.replace(k, v)
    return result
